package com.sh3d.mcp.command.handler;

import com.eteks.sweethome3d.io.HomeFileRecorder;
import com.eteks.sweethome3d.model.Home;
import com.sh3d.mcp.bridge.HomeAccessor;
import com.sh3d.mcp.bridge.SafeHomeReader;
import com.sh3d.mcp.protocol.Response;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.mockito.MockedConstruction;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.concurrent.atomic.AtomicReference;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

import static com.sh3d.mcp.command.handler.TestFixtures.makeRequest;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/** The load-size policy must not restrict validation of a save generated by SH3D. */
class SaveHomeValidationPolicyTest {
    @TempDir
    Path dir;

    @Test
    void saveAcceptsWellFormedXmlLargerThan64MbWhileLoadStillRefusesIt() throws Exception {
        Path file = dir.resolve("large.sh3d");
        AtomicReference<Path> temporary = new AtomicReference<>();
        // Substitute only the exporter, keeping the real save validator and destination write.
        // A compressed XML comment avoids allocating a 64 MB scene or string.
        try (MockedConstruction<HomeFileRecorder> ignored = mockConstruction(HomeFileRecorder.class,
                (recorder, context) -> doAnswer(invocation -> {
                    Path pending = Path.of(invocation.getArgument(1, String.class));
                    temporary.set(pending);
                    writeArchive(pending, true);
                    return null;
                }).when(recorder).writeHome(any(Home.class), anyString()))) {
            Response response = save(file);
            assertTrue(response.isOk(), response.getMessage());
            assertEquals(Files.size(file), response.getData().get("sizeBytes"));
        }
        assertTemporaryRemoved(temporary.get());
        assertThrows(SafeHomeReader.UnsafeHomeFileException.class, () -> SafeHomeReader.validate(file),
                "the 64 MB limit must still apply to loading");
    }

    @Test
    void otherValidationErrorsDoNotClaimThereIsAnInvalidCharacter() throws Exception {
        Path file = Files.write(dir.resolve("existing.sh3d"), new byte[] {1, 2, 3});
        byte[] before = Files.readAllBytes(file);
        AtomicReference<Path> temporary = new AtomicReference<>();
        try (MockedConstruction<HomeFileRecorder> ignored = mockConstruction(HomeFileRecorder.class,
                (recorder, context) -> doAnswer(invocation -> {
                    Path pending = Path.of(invocation.getArgument(1, String.class));
                    temporary.set(pending);
                    writeArchive(pending, false);
                    return null;
                }).when(recorder).writeHome(any(Home.class), anyString()))) {
            Response response = save(file);
            assertTrue(response.isError());
            assertTrue(response.getMessage().contains("Home.xml"), response.getMessage());
            assertFalse(response.getMessage().contains("character"), response.getMessage());
        }
        assertArrayEquals(before, Files.readAllBytes(file));
        assertTemporaryRemoved(temporary.get());
    }

    private static void assertTemporaryRemoved(Path temporary) {
        assertNotNull(temporary);
        assertEquals(Path.of(System.getProperty("java.io.tmpdir")).toAbsolutePath(), temporary.getParent());
        assertTrue(temporary.getFileName().toString().endsWith(".tmp"), temporary.toString());
        assertFalse(Files.exists(temporary), "temporary saves must be removed on success and on refusal");
    }

    private static void writeArchive(Path file, boolean large) throws IOException {
        try (ZipOutputStream zip = new ZipOutputStream(Files.newOutputStream(file))) {
            zip.putNextEntry(new ZipEntry("Home.xml"));
            zip.write("<home><!--".getBytes(StandardCharsets.UTF_8));
            if (large) {
                byte[] block = new byte[8192];
                Arrays.fill(block, (byte) 'a');
                for (int i = 0; i < 64 * 1024 * 1024 / block.length + 1; i++) {
                    zip.write(block);
                }
            }
            zip.write((large ? "--></home>" : "--></wrong>").getBytes(StandardCharsets.UTF_8));
            zip.closeEntry();
        }
    }

    private static Response save(Path file) {
        return new SaveHomeHandler().execute(makeRequest("save_home", "filePath", file.toString()),
                new HomeAccessor(new Home(), null));
    }
}
